'use strict';
// Verify native UI evidence against actual saved project/MCP receipts.
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'../..'),dir=path.join(root,'_codex_mcp_work/chatgpt-dev/59910');
const names=process.argv.slice(2);assert.equal(names.length,2,'Supply before-open and after-explanation receipt filenames');
for(const n of names)assert.match(n,/^paint-options-reopen-[\w-]+\.json$/);
const read=n=>JSON.parse(fs.readFileSync(path.join(dir,n),'utf8'));
const receipts=names.map(read),data=(r,t)=>JSON.parse(r.calls.find(c=>c.tool===t).text);
const states=receipts.map(r=>data(r,'spb_get_state'));
assert.equal(states[0].layers.length,42);assert.equal(states[0].zones.length,5);
assert.deepEqual(states[1].layers,states[0].layers);
assert.deepEqual(states[1].zones,states[0].zones);
assert.deepEqual(receipts[1].images.map(i=>[i.name,i.sha256]),receipts[0].images.map(i=>[i.name,i.sha256]));
assert.deepEqual(receipts[1].candidateManifest,receipts[0].candidateManifest);
assert.deepEqual(receipts[1].ownedModules,receipts[0].ownedModules);
assert.equal(states[0].saved_design_brief.available,false);
assert.equal(states[1].design_options,null,'Saved explanations must not become live proposals');
const savedFile='_release_evidence/chatgpt-dev/59910/projects/ARCA saved design options - private59910.spbproj';
const project=JSON.parse(fs.readFileSync(path.join(root,savedFile),'utf8'));
const brief=project.assistantBrief,restored=states[1].saved_design_brief;
assert.equal(brief.project_id,project.projectId);assert.equal(restored.project_id,project.projectId);
assert.equal(restored.historical,true);assert.deepEqual(restored.turns,brief.turns);
const proposal=brief.turns.find(t=>t.design_proposals).design_proposals;
assert.equal(proposal.items.length,2);assert.equal(proposal.items[1].id,'soft-contrast');
assert.equal(proposal.executable,false);assert.equal(proposal.constraints.no_glitter,true);
assert.deepEqual(proposal.constraints.protected_artwork,['numbers','sponsors']);
assert.deepEqual(data(receipts[1],'spb_assistant_context').saved_design_brief,restored);
const ui=fs.readFileSync(path.join(dir,'saved-options-reopened.txt'),'utf8');
for(const phrase of ['From your saved discussion','Option 2 — Soft black base, muted gold panels','no-glitter','Keep unchanged: numbers, sponsors'])assert.ok(ui.includes(phrase),phrase);
for(const phrase of ['▶ Run','Matching helmet and suit','🎨 Paint by numbers'])assert.ok(!ui.includes(phrase),phrase);
const at=new Date().toISOString(),file='native-saved-options-'+at.replace(/[:.]/g,'-')+'.json';
const result={pass:true,checked_at:at,receipts:names,saved_project:savedFile,native_save_and_verified_reopen:true,actual_Offline_historical_explanation:true,actual_MCP_saved_context:true,live_proposal_state_not_restored:true,unrelated_guidance_suppressed:true,unchanged_layer_records:42,unchanged_zones:5,returned_paint_spec_bytes_exact:true,screenshot:'saved-options-reopened.png',limits:'Private59910 generation. No new subscription inference, full-resolution/export, complete scheme execution, or shared-runtime/Claude parity proof.'};
fs.writeFileSync(path.join(dir,file),JSON.stringify(result,null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({pass:true,receipt:file,scope:result.limits}));
