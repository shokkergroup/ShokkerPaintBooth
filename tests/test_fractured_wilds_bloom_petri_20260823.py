def test_all_forty_actual_outputs_pass_pairwise_chroma_uniqueness():
    descriptors = {}
    for kit, ids in ((bloom.KIT, BLOOM_IDS), (petri.KIT, PETRI_IDS)):
        for fid in ids:
            paint = _RENDERED.get(fid)
            if paint is None:
                size = 256
                source = np.full((size, size, 3), 0.12, np.float32)
                mask = np.ones((size, size), np.float32)
                _, paint_fn = kit.mk(fid)
                paint = (paint_fn(source, (size, size), mask, 913, 1.0, None) * 255).astype(np.uint8)
            descriptors[fid] = _chroma_layout_descriptor(paint)
    nearest = []
    for fid, desc in descriptors.items():
        nearest.append(max(_chroma_layout_similarity(desc, other_desc)
                           for other, other_desc in descriptors.items() if other != fid))
    assert len(nearest) == 40
    assert max(nearest) < 72.0
