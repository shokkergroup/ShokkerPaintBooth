@pytest.mark.parametrize(
    ("kit", "fid"),
    [(bloom.KIT, fid) for fid in BLOOM_IDS] + [(petri.KIT, fid) for fid in PETRI_IDS],
    ids=BLOOM_IDS + PETRI_IDS,
)
def test_renderer_contract_channels_determinism_and_opponent_hue(kit, fid):
    # 256 is a contract probe only.  Native 2048 timing/crops are generated by
    # scripts/spb_wilds_bloom_petri_audit.py and retained as review evidence.
    size = 256
    yy, xx = np.mgrid[:size, :size].astype(np.float32)
    source = np.stack((0.08 + xx / size * 0.12,
                       0.10 + yy / size * 0.10,
                       np.full_like(xx, 0.14)), axis=2).astype(np.float32)
    full = np.ones((size, size), np.float32)
    empty = np.zeros_like(full)
    spec_fn, paint_fn = kit.mk(fid)

    spec = spec_fn((size, size), full, 913, 1.0)
    paint = paint_fn(source, (size, size), full, 913, 1.0, None)
    assert spec.shape == (size, size, 4) and spec.dtype == np.uint8
    assert paint.shape == source.shape and paint.dtype == np.float32
    assert np.isfinite(paint).all() and 0.0 <= float(paint.min()) <= float(paint.max()) <= 1.0

    # Deterministic registry output and canonical neutral/off semantics.
    assert np.array_equal(spec, spec_fn((size, size), full, 913, 1.0))
    assert np.array_equal(paint, paint_fn(source, (size, size), full, 913, 1.0, None))
    assert np.array_equal(spec_fn((size, size), full, 913, 0.0)[:, :, :3],
                          np.broadcast_to(np.uint8([4, 120, 16]), (size, size, 3)))
    assert np.array_equal(spec_fn((size, size), empty, 913, 1.0)[:, :, :3],
                          np.broadcast_to(np.uint8([4, 120, 16]), (size, size, 3)))
    assert np.array_equal(paint_fn(source, (size, size), full, 913, 0.0, None), source)
    assert np.array_equal(paint_fn(source, (size, size), empty, 913, 1.0, None), source)

    partial = np.zeros_like(full)
    partial[64:192, 64:192] = 1.0
    partial_spec = spec_fn((size, size), partial, 913, 1.0)
    partial_paint = paint_fn(source, (size, size), partial, 913, 1.0, None)
    assert np.array_equal(partial_spec[:40, :40, :3],
                          np.broadcast_to(np.uint8([4, 120, 16]), (40, 40, 3)))
    assert np.array_equal(partial_paint[:40, :40], source[:40, :40])

    channels = spec[:, :, :3]
    authored_levels = (microkit._M_LEVELS, microkit._R_LEVELS,
                       microkit._C_LEVELS)
    for channel in range(3):
        data = channels[:, :, channel]
        assert float(data.std()) >= 20.0
        assert int(data.max()) - int(data.min()) >= 150
        assert _tier_count(data, authored_levels[channel]) == 8

    # The three authored phase ladders are not copies of one another.
    assert all(len(np.unique(levels)) == 8 for levels in
               (microkit._M_LEVELS, microkit._R_LEVELS, microkit._C_LEVELS))
    flat = channels.reshape(-1, 3).astype(np.float32)
    correlations = np.corrcoef(flat, rowvar=False)
    assert max(abs(float(correlations[0, 1])),
               abs(float(correlations[0, 2])),
               abs(float(correlations[1, 2]))) < 0.75

    # Saturation-weighted phase hue excludes a white-only highlight.  Each
    # finish must expose a genuine opponent hue between its clear- and
    # metal-led material populations.
    material = _material_hue_separation((paint * 255.0).astype(np.uint8), channels)
    assert material["opponentHueTravelDegrees"] >= 55.0
    assert material["whiteHighlightProofScore"] >= 30.0
    _RENDERED[fid] = (paint * 255.0).astype(np.uint8)


def test_six_fine_mark_families_are_present_and_distinct():
    fields = bloom.KIT.signature_cached(BLOOM_IDS[0])
    fam = fields[2]
    assert fam.shape == (6, bloom.KIT.GEN, bloom.KIT.GEN)
    # No two mark alphabets may collapse to the same mask.
    resized = [cv2.resize(x, (96, 96), interpolation=cv2.INTER_AREA).ravel()
               for x in fam]
    for i in range(6):
        for j in range(i + 1, 6):
            assert not np.allclose(resized[i], resized[j], atol=1e-3)


def test_every_dominant_mark_box_is_8_to_32_pixels_at_native_2048():
    # Primitive support is at least 0.55 of its cell and never exceeds it.
    # Query the exact pitch function used by the renderer for all profiles.
    scale = 2048.0 / bloom.KIT.GEN
    pitches = [pitch for profile in range(20)
               for pitch in microkit._cell_pitches(profile)]
    assert min(pitches) * 0.55 * scale >= 8.0
    assert max(pitches) * scale <= 32.0


@pytest.mark.parametrize(
    ("kit", "fid"),
    [(bloom.KIT, fid) for fid in BLOOM_IDS] + [(petri.KIT, fid) for fid in PETRI_IDS],
    ids=[f"scale-{fid}" for fid in BLOOM_IDS + PETRI_IDS],
)
def test_every_visible_role_zone_p95_is_at_most_32_native_pixels(kit, fid):
    """Equal-density color/glyph routes count as visible owner-eye features.

    This intentionally tests the stricter physical scale, not merely the small
    glyph boxes: a continuous lead/counter role zone may not hide an 80-250 px
    macro band made from compliant dots.  SPB-WILDS owner-eye gate 2026-08-23.
    """
    d = kit.ALL[fid]
    variant = int(d.get("wild_variant", d["wild_profile"]))
    organization = microkit._hue_composition(
        kit.GEN, int(d["seed"]), variant,
    )[1]
    route = organization >= 0.5
    native_scale = 2048.0 / kit.GEN
    p95_thickness = []
    for region in (route, ~route):
        distance = cv2.distanceTransform(region.astype(np.uint8), cv2.DIST_L2, 5)
        p95_thickness.append(
            float(np.percentile(distance[region], 95.0)) * 2.0 * native_scale
        )
    assert max(p95_thickness) <= 32.01


